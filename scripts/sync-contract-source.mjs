#!/usr/bin/env node
/**
 * sync-contract-source.mjs — copy the ChainFundedPool source into a module that
 * BOTH the frontend (the Contract Explorer viewer) and the serverless
 * grounding agent (api/contract-agent.js) import, so they can never drift from
 * each other. Runs as part of `npm run build`; commit the generated output too.
 *
 * Single source of truth: contracts/contracts/ChainFundedPool.sol. The deployed
 * address is read from env at runtime (VITE_REWARDS_POOL_ADDRESS) — not embedded
 * here — so the viewer always links to the live, verified contract.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(__dirname, '../contracts/contracts/ChainFundedPool.sol');
const OUT = resolve(__dirname, '../src/data/contractSource.js');

const source = readFileSync(SRC, 'utf8');
const lines = source.split('\n').length;
const solidity = (source.match(/pragma solidity\s+([^;]+);/) || [, 'unknown'])[1].trim();

const module = `// AUTO-GENERATED by scripts/sync-contract-source.mjs — do not edit by hand.
// Regenerate with: node scripts/sync-contract-source.mjs (runs in \`npm run build\`).
// Source of truth: contracts/contracts/ChainFundedPool.sol
export const CONTRACT_META = ${JSON.stringify({ name: 'ChainFundedPool.sol', solidity, lines }, null, 2)};
export const CONTRACT_SOURCE = ${JSON.stringify(source)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, module);
console.log(`✓ contract source synced → src/data/contractSource.js (${lines} lines, Solidity ${solidity})`);
