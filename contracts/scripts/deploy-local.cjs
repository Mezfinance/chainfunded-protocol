/**
 * deploy-local.js — Deploy all contracts + seed test data on local Hardhat node.
 *
 * Called by local-env.js via: npx hardhat run scripts/deploy-local.cjs --network localhost
 *
 * Seeds:
 *   - 3 LP deposits ($500K, $200K, $100K)
 *   - 5 challenge registrations across 2 traders
 *   - 1 admin whitelist account
 *   - 1 affiliate referral
 *   - CFG distributor registrations for all challenges
 *   - 1 CFND stake in LP rewards
 *   - 1 completed payout (ECDSA signed)
 */

const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

const DAY  = 86_400n;
const YEAR = 365n * DAY;
const SEASON_DURATION = 182n * DAY;

const u = (n) => BigInt(n) * 1_000_000n;
const c = (n) => ethers.parseEther(String(n));
const id = (s) => s.toString(16).padStart(24, "0");

async function signPayout(signer, poolAddr, p) {
  const hash = ethers.keccak256(ethers.AbiCoder.defaultAbiCoder().encode(
    ["address","string","uint256","uint256","uint256","uint256","uint256",
     "string","uint256","uint256","address"],
    [p.trader, p.accountId, p.gross, p.dailyLoss, p.drawdown,
     p.days, p.bestDay, p.payoutId, p.deadline, p.chainId, poolAddr]
  ));
  return signer.signMessage(ethers.getBytes(hash));
}

async function main() {
  const signers = await ethers.getSigners();
  const [deployer, payoutSigner, labs, guardian,
         lp1, lp2, trader1, trader2, affiliate1, reporter,
         teamMember, investor] = signers;

  const chainId = (await ethers.provider.getNetwork()).chainId;
  const out = { _comment: "Auto-generated by deploy-local.js", chainId: Number(chainId) };

  console.log("=== Deploying all contracts to localhost ===\n");

  // ── 1. MockUSDC ────────────────────────────────────────────────────────────
  const usdc = await (await ethers.getContractFactory("MockUSDC")).deploy(deployer.address);
  out.usdc = await usdc.getAddress();
  console.log("MockUSDC:", out.usdc);

  // Fund all test accounts with USDC
  for (const s of [lp1, lp2, trader1, trader2, affiliate1]) {
    await usdc.transfer(s.address, u(5_000_000));
  }

  // ── 2. ChainFundedPool ─────────────────────────────────────────────────────
  const pool = await (await ethers.getContractFactory("ChainFundedPool")).deploy(
    out.usdc, [payoutSigner.address], 1, labs.address, deployer.address
  );
  out.pool = await pool.getAddress();
  await pool.updateGuardian(guardian.address);
  console.log("ChainFundedPool:", out.pool);

  const cfndToken = await ethers.getContractAt("CFNDToken", await pool.cfndTokenAddress());
  out.cfndToken = await cfndToken.getAddress();

  // ── 3. Governance stack ────────────────────────────────────────────────────
  const timelock = await (await ethers.getContractFactory("TimelockController")).deploy(60, [], [], deployer.address);
  out.timelock = await timelock.getAddress();

  const cfgToken = await (await ethers.getContractFactory("CFGToken")).deploy(deployer.address);
  out.cfgToken = await cfgToken.getAddress();

  const governor = await (await ethers.getContractFactory("CFGGovernor")).deploy(
    out.cfgToken, out.timelock, 10, 50, c("1")
  );
  out.governor = await governor.getAddress();

  // Roles
  await (await timelock.grantRole(await timelock.PROPOSER_ROLE(), out.governor)).wait();
  await (await timelock.grantRole(await timelock.CANCELLER_ROLE(), out.governor)).wait();
  await (await timelock.grantRole(await timelock.EXECUTOR_ROLE(), ethers.ZeroAddress)).wait();
  await (await timelock.revokeRole(await timelock.DEFAULT_ADMIN_ROLE(), deployer.address)).wait();
  console.log("Governance:", out.timelock, out.cfgToken, out.governor);

  // ── 4. Vesting ─────────────────────────────────────────────────────────────
  const now = BigInt((await ethers.provider.getBlock("latest")).timestamp);
  const V = await ethers.getContractFactory("CFGVesting");

  const vestTeam = await V.deploy(out.cfgToken, teamMember.address, c("20000000"), now + 10n, 182n * DAY, 4n * YEAR);
  const vestInvestor = await V.deploy(out.cfgToken, investor.address, c("1800000"), now + 10n, 0n, YEAR);
  out.vestingTeam = [await vestTeam.getAddress()];
  out.vestingInvestor = [await vestInvestor.getAddress()];
  out.vestingAdvisor = [];
  console.log("Vesting: team", out.vestingTeam[0], "investor", out.vestingInvestor[0]);

  // ── 5. Rewards contracts ───────────────────────────────────────────────────
  const distributor = await (await ethers.getContractFactory("CFGDistributor")).deploy(
    out.cfgToken, out.pool, deployer.address
  );
  out.distributor = await distributor.getAddress();

  const lpRewards = await (await ethers.getContractFactory("CFGLPRewards")).deploy(
    out.cfgToken, out.pool, out.usdc, deployer.address
  );
  out.lpRewards = await lpRewards.getAddress();
  console.log("Rewards:", out.distributor, out.lpRewards);

  // ── 6. Mint 100M CFG ──────────────────────────────────────────────────────
  await (await cfgToken.initialMint(
    [out.timelock, deployer.address, out.vestingTeam[0], out.vestingInvestor[0], investor.address, labs.address],
    [c("51000000"), c("25000000"), c("20000000"), c("1800000"), c("200000"), c("2000000")]
  )).wait();

  await cfgToken.transfer(out.distributor, c("15000000"));
  await cfgToken.transfer(out.lpRewards, c("10000000"));

  // ── 7. Config ──────────────────────────────────────────────────────────────
  await pool.setCfndTransferWhitelist(out.lpRewards, true);
  await distributor.setReporter(reporter.address, true);

  // Create seasons (start immediately)
  const seasonStart = BigInt((await ethers.provider.getBlock("latest")).timestamp) + 10n;
  let sStart = seasonStart;
  for (let i = 0; i < 10; i++) {
    await distributor.createSeason(sStart, 0n);
    await lpRewards.startSeason(sStart, 0n);
    sStart += SEASON_DURATION;
  }
  console.log("10 seasons created, starting at:", Number(seasonStart));

  // ── 8. Seed: LP deposits ───────────────────────────────────────────────────
  console.log("\n=== Seeding test data ===\n");

  await usdc.connect(lp1).approve(out.pool, u(500_000));
  await pool.connect(lp1).deposit(u(500_000), 0);
  console.log("LP1 deposited $500K");

  await usdc.connect(lp2).approve(out.pool, u(200_000));
  await pool.connect(lp2).deposit(u(200_000), 0);
  console.log("LP2 deposited $200K");

  // ── 9. Seed: Challenge registrations ───────────────────────────────────────
  // Advance past season start (chain may have moved beyond it during deployment)
  const currentTs = BigInt((await ethers.provider.getBlock("latest")).timestamp);
  const targetTs = currentTs > seasonStart ? currentTs + 1n : seasonStart;
  await ethers.provider.send("evm_setNextBlockTimestamp", [Number(targetTs)]);
  await ethers.provider.send("evm_mine");

  const challenges = [
    { trader: trader1, id: id(1), size: u(1_000),  fee: u(30),  phase: 1 },
    { trader: trader1, id: id(2), size: u(1_000),  fee: u(30),  phase: 1 },
    { trader: trader2, id: id(3), size: u(10_000), fee: u(155), phase: 1 },
    { trader: trader2, id: id(4), size: u(1_000),  fee: u(30),  phase: 1 },
  ];

  for (const ch of challenges) {
    await usdc.connect(ch.trader).approve(out.pool, ch.fee);
    await pool.connect(ch.trader).registerChallenge(ch.fee, ch.id, ch.size, ch.phase, ethers.ZeroAddress, 0);
    // Auto-register for CFG points (permissionless)
    await distributor.connect(ch.trader).recordRegistration(ch.id, false);
    console.log(`Challenge ${ch.id} registered by ${ch.trader === trader1 ? "trader1" : "trader2"} ($${Number(ch.size) / 1e6})`);
  }

  // Affiliate referral
  await usdc.connect(trader2).approve(out.pool, u(30));
  await pool.connect(trader2).registerChallenge(u(30), id(5), u(1_000), 1, affiliate1.address, 0);
  await distributor.connect(trader2).recordRegistration(id(5), false);
  console.log("Challenge", id(5), "registered with affiliate referral");

  // Admin whitelist account
  await pool.adminRegisterChallenge(trader1.address, id(10), u(1_000), 1);
  await distributor.connect(reporter).recordRegistration(id(10), true);
  console.log("Whitelist account", id(10), "registered");

  // ── 10. Seed: Payout (ECDSA signed) ────────────────────────────────────────
  const payoutParams = {
    trader: trader1.address,
    accountId: id(1),
    gross: u(150),
    dailyLoss: 200n,
    drawdown: 500n,
    days: 5n,
    bestDay: 4000n,
    payoutId: "seed-payout-001",
    deadline: BigInt((await ethers.provider.getBlock("latest")).timestamp) + 3600n,
    chainId,
  };
  const sig = await signPayout(payoutSigner, out.pool, payoutParams);
  await pool.connect(trader1).claimPayout(
    id(1), payoutParams.gross, payoutParams.dailyLoss, payoutParams.drawdown,
    payoutParams.days, payoutParams.bestDay, payoutParams.payoutId,
    payoutParams.deadline, [sig], 0
  );
  console.log("Payout executed for challenge", id(1), "($150 gross, $120 to trader)");

  // ── 11. Seed: CFND staking ─────────────────────────────────────────────────
  await lpRewards.connect(lp1).stake(u(100_000));
  console.log("LP1 staked 100K CFND in CFGLPRewards");

  // Advance time 1 hour so CFG accrues
  await ethers.provider.send("evm_increaseTime", [3600]);
  await ethers.provider.send("evm_mine");
  console.log("Advanced 1 hour for CFG accrual");

  // ── 12. Output ─────────────────────────────────────────────────────────────
  out.testAccounts = {};
  const names = ["deployer","payoutSigner","labsWallet","guardian","lp1","lp2",
                 "trader1","trader2","affiliate1","reporter","teamMember","investor"];
  names.forEach((name, i) => {
    out.testAccounts[name] = signers[i].address;
  });

  const outPath = path.resolve(__dirname, "../../test/setup/contracts.json");
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2));
  console.log("\n=== Deploy complete ===");
  console.log(`Contracts written to ${outPath}`);
  console.log(`${Object.keys(out).filter(k => !k.startsWith("_") && k !== "testAccounts" && k !== "chainId").length} contracts deployed`);

  // Print summary
  console.log("\nAddresses:");
  for (const [k, v] of Object.entries(out)) {
    if (k.startsWith("_") || k === "testAccounts" || k === "chainId") continue;
    if (Array.isArray(v)) console.log(`  ${k}: [${v.join(", ")}]`);
    else console.log(`  ${k}: ${v}`);
  }

  console.log("\nSeeded data:");
  console.log("  LP deposits: 3 ($500K + $200K + staking)");
  console.log("  Challenges: 6 (4 paid + 1 affiliate + 1 whitelist)");
  console.log("  CFG registrations: 6");
  console.log("  Payouts: 1 ($150 gross)");
  console.log("  CFND staked: 100K (1 hour of CFG accrual)");
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
